exec "${TMM_PYTHON:-/data0/pretrained/env_humanomniv2/bin/python}" -B - "$0" "$@" <<'PYCODE'
"""Prepare, check, run and score source-linked evidence records."""
import os as _entry_os
import sys as _entry_sys
__file__ = _entry_os.path.abspath(_entry_sys.argv[1])
_entry_sys.argv = [_entry_sys.argv[1], *_entry_sys.argv[2:]]
import argparse
import csv
import gc
import json
import os
import sys
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'code'))
if Path('/data0/pretrained/tmm_phi4_deps').is_dir():
    sys.path.insert(0, '/data0/pretrained/tmm_phi4_deps')
from tmm.support import evidence_records as evaluation
from tmm.support.data import digest, load_records, write_json

MODELS = ('QT', 'G3', 'QO', 'PM')


def export(base, coverage):
    tex = ['% Generated by scripts/evidence_records.sh; reference agreement, not free-form citation support.',
           f"\\SetResult{{recordsN}}{{{coverage['participants']}}}",
           f"\\SetResult{{recordsTurns}}{{{coverage['turns']}}}",
           f"\\SetResult{{recordsSpans}}{{{coverage['reference_records']}}}"]
    rows = []
    for model in MODELS:
        path = base/model/'metrics.json'
        if not path.exists():
            continue
        metrics = json.loads(path.read_text())
        rows.append({'model': model, **{k: metrics['percentages'][k] for k in evaluation.METRICS}})
        for key, suffix in zip(evaluation.METRICS, ('Evidence', 'Fields', 'Complete')):
            tex.append(f"\\SetResult{{records{model}{suffix}}}{{{metrics['percentages'][key]:.2f}}}")
    # Called by explicit score stage, after parallel model processes finish.
    (base/'table2_values.tex').write_text('\n'.join(tex)+'\n', encoding='utf-8')
    with (base/'table2.csv').open('w', newline='', encoding='utf-8') as handle:
        writer = csv.DictWriter(handle, fieldnames=['model', *evaluation.METRICS])
        writer.writeheader()
        writer.writerows(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stage', choices=('prepare', 'check', 'run', 'score'), default='run')
    parser.add_argument('--models', nargs='+', choices=MODELS, default=list(MODELS))
    parser.add_argument('--gpu', type=int, default=3)
    parser.add_argument('--output', type=Path, default=ROOT/'runs/table2')
    args = parser.parse_args()
    os.environ['CUDA_VISIBLE_DEVICES'] = str(args.gpu)
    config = json.loads((ROOT/'configs/experiments.json').read_text(encoding='utf-8-sig'))
    items, ontology, coverage = evaluation.prepare(ROOT, verify_sources=args.stage != 'prepare')
    task = config['tasks']['daic'] | {'max_turn_seconds': None}
    protocol = {'schema': 'evidence-records-v1', 'items': items, 'ontology': ontology,
                'task': task, 'models': {m: config['models'][m] for m in MODELS}, 'generation': config['protocol'],
                'matching': 'Exact source substring; character IoU >= 0.5; one-to-one maximum-cardinality then overlap.',
                'fields': 'Four fields per reference; unmatched references receive zero; equal participant mean.',
                'field_normalization': 'Category names are compared after stripping outer whitespace and case folding; no semantic alias repair.',
                'f1': '2*matched/(reference+predicted); complete match additionally requires all four fields.',
                'uncertainty': '2000 participant bootstrap resamples, seed 27',
                'code': {str(p.relative_to(ROOT)): digest(p.read_text(encoding='utf-8')) for p in
                         [Path(__file__), ROOT/'code/tmm/support/evidence_records.py', ROOT/'code/tmm/support/models.py', ROOT/'code/tmm/support/data.py']}}
    protocol['fingerprint'] = digest(protocol)
    base = args.output
    protocol_path = base/'protocol.json'
    if protocol_path.exists() and json.loads(protocol_path.read_text()) != protocol:
        raise ValueError('Frozen protocol changed; do not mix runs in this directory')
    if args.stage == 'prepare':
        write_json(protocol_path, protocol)
        write_json(base/'coverage.json', coverage)
        print(json.dumps(coverage, indent=2))
        return
    records = [r for r in load_records(ROOT, task) if r['split'] == 'test' and r['id'] in {i['record_id'] for i in items}]
    by_record = {r['id']: r for r in records}
    for model in args.models:
        if not Path(config['models'][model]['path']).is_dir():
            raise ValueError('Checkpoint missing: '+model)
        track = 'T' if config['models'][model]['kind'] == 'text' else 'A+T'
        for item in items:
            evaluation.exposed_views(item, by_record[item['record_id']], track)
    if args.stage == 'check':
        write_json(protocol_path, protocol)
        write_json(base/'coverage.json', coverage)
        print(json.dumps({'ready': True, 'models': args.models, 'turns': len(items), 'coverage': coverage}))
        return
    if not protocol_path.exists():
        raise ValueError('Run --stage check once before starting inference')
    from tmm.support.experiments import input_provenance
    for model in args.models:
        out = base/model
        provenance = input_provenance(records, config['models'][model])
        provenance_path = out/'inputs.json'
        if provenance_path.exists() and json.loads(provenance_path.read_text()) != provenance:
            raise ValueError('Sources or checkpoint changed')
        write_json(provenance_path, provenance)
        backbone = None
        try:
            if args.stage == 'run':
                from tmm.support.models import Backbone
                import torch
                torch.manual_seed(27)
                backbone = Backbone(config['models'][model], config['protocol'], 'Extract source-linked evidence records.')
            track = 'T' if config['models'][model]['kind'] == 'text' else 'A+T'
            responses = evaluation.collect(backbone, items, records, track, ontology, out/'predictions.json')
            metrics = evaluation.summarize(items, responses)
            write_json(out/'metrics.json', metrics)
            print(json.dumps({'model': model, 'metrics': metrics['percentages'], 'output': str(out)}), flush=True)
        finally:
            del backbone
            gc.collect()
            if 'torch' in sys.modules and sys.modules['torch'].cuda.is_available():
                sys.modules['torch'].cuda.empty_cache()
    if args.stage == 'score':
        export(base, coverage)


if __name__ == '__main__':
    main()
PYCODE
